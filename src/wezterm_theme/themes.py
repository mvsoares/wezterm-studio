def _norm_slug(s: str) -> str:
    return re.sub(r"[\s_-]+", " ", s.lower()).strip()


def find_theme(query: str, min_substr_len: int = 1) -> dict[str, Any] | None:
    """Find a theme by numeric ID ('10', '#10', '01'), slug ('cyberpunk-edgerunners'), or name substring."""
    q = query.strip()
    q_num = q.lstrip("#").strip()
    if q_num.isdigit():
        return get_theme_by_id(int(q_num))
    q_norm = _norm_slug(q)
    if not q_norm:
        return None
    for t in THEMES:
        if _norm_slug(t["name"]) == q_norm:
            return t
    if len(q_norm) < min_substr_len:
        return None
    for t in THEMES:
        if q_norm in _norm_slug(t["name"]):
            return t
    return None


def filter_themes(themes: list[dict[str, Any]], filter_query: str) -> list[dict[str, Any]]:
    """Filter themes by ID (#30 / 30), slug, name, category, description, or style."""
    if not filter_query:
        return themes
    q = filter_query.lower().strip()
    q_slug = re.sub(r"[\s_-]+", " ", q)
    num_match = None
    if q.startswith("#") and q[1:].isdigit():
        num_match = int(q[1:])
    elif q.isdigit():
        num_match = int(q)

    return [
        t
        for t in themes
        if (
            (num_match is not None and t["id"] == num_match)
            or q in t["name"].lower()
            or q_slug in re.sub(r"[\s_-]+", " ", t["name"].lower())
            or q in t["category"].lower()
            or q in t.get("description", "").lower()
            or q in t.get("style", "").lower()
        )
    ]



def _hover_pair(bg: str, fg: str) -> tuple[str, str]:
    """Compute a subtle, WCAG-checked hover background/foreground pair."""
    h = bg.lstrip("#")
    rgb = [int(h[i : i + 2], 16) for i in (0, 2, 4)]
    if _luminance(bg) < 0.35:
        shifted = [min(255, int(round(c + (255 - c) * 0.14))) for c in rgb]
    else:
        shifted = [max(0, int(round(c * 0.89))) for c in rgb]
    h_bg = "#{:02x}{:02x}{:02x}".format(*shifted)
    return h_bg, readable_fg(h_bg, fg)

def _luminance(hex_color: str) -> float:
    h = hex_color.lstrip("#")
    c = [int(h[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def contrast_ratio(a: str, b: str) -> float:
    hi, lo = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


# WCAG AA for large/bold text. Tab titles are short bold-ish labels, and 4.5:1
# would turn the white-on-Google-blue look (3.56:1) black in dozens of themes.
MIN_TAB_CONTRAST = 3.0


def readable_fg(bg: str, fg: str) -> str:
    """Return fg if readable on bg, otherwise whichever of white/near-black reads best."""
    if contrast_ratio(bg, fg) >= MIN_TAB_CONTRAST:
        return fg
    return max(("#ffffff", "#1a1a1a"), key=lambda c: contrast_ratio(bg, c))


